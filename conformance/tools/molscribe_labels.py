"""Expand substituent labels with MolScribe's condensed-formula code.

Usage:

    python -I molscribe_labels.py <molscribe-checkout> <labels.txt> <out.toml>

Reads `<label> <left|right>` lines, expands each label with MolScribe's
`get_smiles_from_symbol` as if the label carried one single bond to the parent
structure, puts a `*` on the atom that carries that bond, and writes the RDKit
canonical SMILES, or the reason there is none, as TOML for
`moiety differential`.

Needs rdkit. MolScribe's `SmilesPE` import is only used by functions this
script never calls, so it is replaced with a stub instead of being installed.
"""

import importlib.util
import json
import subprocess
import sys
import types
from pathlib import Path

import rdkit
from rdkit import Chem, RDLogger


def load_chemistry(checkout: Path) -> types.ModuleType:
    package = types.ModuleType("molscribe")
    package.__path__ = [str(checkout / "molscribe")]
    sys.modules["molscribe"] = package
    tokenizer = types.ModuleType("SmilesPE.pretokenizer")
    tokenizer.atomwise_tokenizer = list
    sys.modules["SmilesPE"] = types.ModuleType("SmilesPE")
    sys.modules["SmilesPE.pretokenizer"] = tokenizer
    for name in ("constants", "chemistry"):
        spec = importlib.util.spec_from_file_location(
            f"molscribe.{name}", checkout / "molscribe" / f"{name}.py"
        )
        module = importlib.util.module_from_spec(spec)
        sys.modules[f"molscribe.{name}"] = module
        spec.loader.exec_module(module)
    return sys.modules["molscribe.chemistry"]


class SingleBond:
    def GetBondTypeAsDouble(self) -> float:
        return 1.0


def expand(chemistry: types.ModuleType, label: str) -> dict:
    route = "abbreviation" if label in chemistry.ABBREVIATIONS else "formula"
    smiles = chemistry.get_smiles_from_symbol(label, None, None, [SingleBond()])
    if smiles is None:
        return {"route": route, "error": "no expansion"}
    molecule = Chem.MolFromSmiles("*" + smiles)
    if molecule is None:
        return {"route": route, "error": f"invalid SMILES {smiles}"}
    return {"route": route, "smiles": Chem.MolToSmiles(Chem.RemoveHs(molecule))}


def read_labels(path: Path) -> list[tuple[str, str]]:
    labels = []
    for line in path.read_text(encoding="utf-8").splitlines():
        content = line.split("#", 1)[0].strip()
        if not content:
            continue
        text, side = content.split()
        if side not in ("left", "right"):
            raise SystemExit(f"bad side {side!r} for {text!r}")
        labels.append((text, side))
    return labels


def toml_string(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


def main() -> None:
    if len(sys.argv) != 4:
        raise SystemExit(__doc__)
    checkout, labels_path, out_path = (Path(arg) for arg in sys.argv[1:])
    RDLogger.DisableLog("rdApp.*")
    chemistry = load_chemistry(checkout)
    commit = subprocess.run(
        ["git", "-C", str(checkout), "rev-parse", "HEAD"],
        capture_output=True,
        text=True,
        check=True,
    ).stdout.strip()
    lines = [
        "# Generated by conformance/tools/molscribe_labels.py; do not edit by hand.",
        "",
        f"source = {toml_string(f'MolScribe {commit}')}",
        f"toolkit = {toml_string(f'RDKit {rdkit.__version__}')}",
    ]
    for text, side in read_labels(labels_path):
        result = expand(chemistry, text)
        lines += ["", "[[label]]", f"text = {toml_string(text)}", f"side = {toml_string(side)}"]
        lines += [f"{key} = {toml_string(value)}" for key, value in result.items()]
    out_path.write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
